let failed = false;
for (const [path, contents] of [
  ["README.md", readme],
  ["llms.txt", short],
  ["llms-full.txt", full],
]) {
  if (check) {
    let actual;
    try {
      actual = readFileSync(path, "utf8").replaceAll("\r\n", "\n");
    } catch {
      actual = null;
    }
    if (actual !== contents) {
      console.error(`${path} is stale; run just sync-discovery`);
      failed = true;
    }
  } else writeFileSync(path, contents);
}
if (failed) process.exitCode = 1;
